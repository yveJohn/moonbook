    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id bigint NOT NULL REFERENCES novel_books(id),
    status varchar(20) NOT NULL CHECK (status IN ('running','pending','approved','rejected','applied','failed','retried','recovered','expired')),
    trigger_type varchar(20) NOT NULL CHECK (trigger_type IN ('auto_scan','manual','regenerate')),
    input_mode varchar(32) NOT NULL CHECK (input_mode IN ('chapter_summary','chunk_summary','sampled_cleaned_text')),
    input_digest char(64) NOT NULL,
    input_snapshot jsonb NOT NULL,
    original_snapshot jsonb NOT NULL,
    suggested_snapshot jsonb,
    review_snapshot jsonb,
    raw_response text NOT NULL DEFAULT '',
    raw_response_expires_at timestamptz,
    reviewer_name varchar(100) NOT NULL DEFAULT '',
    reject_reason varchar(1000) NOT NULL DEFAULT '',
    reviewed_at timestamptz,
    applied_at timestamptz,
    error_message varchar(1000) NOT NULL DEFAULT '',
    failure_type varchar(64) NOT NULL DEFAULT '',
    retry_source_id bigint REFERENCES novel_book_profile_suggestion(id),
    retry_target_id bigint REFERENCES novel_book_profile_suggestion(id),
