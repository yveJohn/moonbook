CREATE TABLE novel_book_profile_config (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auto_scan_enabled boolean NOT NULL DEFAULT false,
    auto_apply_enabled boolean NOT NULL DEFAULT false,
    process_ai_refusal_enabled boolean NOT NULL DEFAULT false,
    ai_config_id bigint NOT NULL REFERENCES novel_ai_config(id),
    refusal_fallback_ai_config_id bigint REFERENCES novel_ai_config(id),
    system_prompt text NOT NULL,
    temperature numeric(4,2) NOT NULL DEFAULT 0.10 CHECK (temperature BETWEEN 0 AND 2),
    max_tokens integer NOT NULL DEFAULT 2000 CHECK (max_tokens BETWEEN 1 AND 1000000),
    timeout_seconds integer NOT NULL DEFAULT 120 CHECK (timeout_seconds BETWEEN 1 AND 1800),
    request_interval_ms integer NOT NULL DEFAULT 0 CHECK (request_interval_ms BETWEEN 0 AND 600000),
    retry_count integer NOT NULL DEFAULT 1 CHECK (retry_count BETWEEN 0 AND 20),
    scan_batch_size integer NOT NULL DEFAULT 5 CHECK (scan_batch_size BETWEEN 1 AND 1000),
    max_input_chars integer NOT NULL DEFAULT 60000 CHECK (max_input_chars BETWEEN 1000 AND 1000000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
